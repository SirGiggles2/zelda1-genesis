"""Derive immutable MP poses from installed CHR and the runtime descriptors.

NES source: authenticated common/demo banks and captured Link OAM descriptors.
Drained C: sprite_render.c:upload_pose_recolor (T367 frozen reference in audit).
Coverage: both profiles, three identities, eight walk/magic and four attack poses.
Stance: EXTEND; move an unchanged pixel transform from gameplay into the build.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]


def array(path, symbol):
    text = path.read_text(encoding='utf-8')
    match = re.search(r'const unsigned char '+symbol+r'\[(\d+)\]\s*=\s*\{(.*?)\};', text, re.S)
    if not match:
        raise ValueError(f'missing byte array {symbol}: {path}')
    data = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})\b', match[2]))
    if len(data) != int(match[1]):
        raise ValueError(f'array length mismatch: {symbol}')
    return data


def descriptors(text, symbol, count):
    body = re.search(r'static const link_pose_def_t '+symbol+r'\[[^]]+\]\s*=\s*\{(.*?)\n\};', text, re.S)[1]
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    rows = [[int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)u?', row)]
            for row in re.findall(r'\{\s*\{[^}]+\}\s*,[^}]+\}', body)]
    if len(rows) != count or any(len(row) != 5 for row in rows):
        raise ValueError(f'unsupported descriptor layout: {symbol}')
    return rows


def transform(pose, common, demo, color):
    result = bytearray()
    for index, tile in enumerate(pose[:4]):
        source = common[tile*32:tile*32+32] if tile < 112 else demo[(tile-112)*32:(tile-112)*32+32]
        if len(source) != 32:
            raise ValueError('descriptor points outside installed CHR')
        for row in range(8):
            pixels = [n for b in source[row*4:row*4+4] for n in (b >> 4, b & 15)]
            if pose[4] & (1 << index):
                pixels.reverse()
            pixels = [color if n == 1 else n for n in pixels]
            result.extend((pixels[i] << 4) | pixels[i+1] for i in range(0, 8, 2))
    return bytes(result)


def generate(root=ROOT):
    render = root/'src/game/world/render/sprite_render.c'
    common = root/'data/chr/common.c'
    demo = root/'data/chr/demo.c'
    redux = root/'build/generated/core_redux_chr.c'
    poses = []
    for name, count in [('link_poses', 8), ('link_poses_magic', 8), ('attack_poses', 4), ('lift_poses', 2)]:
        poses += descriptors(render.read_text(encoding='utf-8'), name, count)
    banks = [(array(common, 'common_chr'), array(demo, 'demo_chr')),
             (array(redux, 'core_redux_common_chr'), array(redux, 'core_redux_demo_chr'))]
    data = b''.join(transform(pose, c, d, color) for c, d in banks
                    for color in (4, 8, 12, 5) for pose in poses)
    assert len(data) == 22528
    output = root/'build/generated/mp_link_poses.c'
    # u16 storage guarantees an even ROM DMA source on the actual big-endian CPU.
    words = [(data[i] << 8) | data[i+1] for i in range(0, len(data), 2)]
    source = '/* Generated by mp_link_poses.py; installed ROM-derived assets. */\n'
    source += 'const unsigned short mp_link_pose_words[2][4][22][64] = {\n'
    for profile in range(2):
        source += ' {\n'
        for identity in range(4):
            source += '  {\n'
            for pose in range(22):
                start = ((profile*4+identity)*22+pose)*64
                source += '   {' + ','.join(f'0x{w:04X}' for w in words[start:start+64]) + '},\n'
            source += '  },\n'
        source += ' },\n'
    source += '};\n'
    if not output.exists() or output.read_text(encoding='ascii') != source:
        output.write_text(source, encoding='ascii')
    manifest = dict(schema=1, bytes=len(data), sha256=hashlib.sha256(data).hexdigest(),
                    dependencies={str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest()
                                  for p in (render, common, demo, redux, root/'tools/converter/mp_link_poses.py')})
    output.with_suffix('.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='ascii')
    return data, poses, banks


if __name__ == '__main__':
    data, _, _ = generate()
    print(f'MP poses: {len(data)} ROM bytes derived from installed assets')
