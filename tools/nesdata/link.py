"""Write the .nesdata link inputs from the piece registry.

- write_asm: build/nesdata/nesdata.s, one .incbin per piece in registry order.
- write_layout: src/nesdata/nesdata_layout.h, sizes only (no content).
- check_sizes: every piece file present with its registered size.

T-419 Task 2.
"""
from __future__ import annotations

from pathlib import Path
from typing import Iterable

from tools.nesdata.pieces import Piece


def check_sizes(pieces: Iterable[Piece], root: Path) -> list[str]:
    errors = []
    for p in pieces:
        f = root / p.path
        if not f.is_file():
            errors.append(f"nesdata piece {p.name}: missing {p.path}")
        elif f.stat().st_size != p.size:
            errors.append(f"nesdata piece {p.name}: {f.stat().st_size} bytes, registry says {p.size}")
    return errors


def write_asm(pieces: Iterable[Piece], out: Path, root: Path) -> None:
    lines = ['.section .nesdata,"a"', ""]
    for p in pieces:
        incbin = (root / p.path).resolve().as_posix()
        lines += [f".balign {p.align}", f".global {p.symbol}", f"{p.symbol}:", f'.incbin "{incbin}"',
                  f".type {p.symbol}, @object", f".size {p.symbol}, {p.size}", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_layout(pieces: Iterable[Piece], out: Path) -> None:
    lines = ["/* Generated by tools/nesdata/link.py from tools/nesdata/pieces.py; do not edit.",
             " * Sizes of the NES-derived .nesdata pieces. Numbers only, no ROM content. */",
             "#ifndef NESDATA_LAYOUT_H", "#define NESDATA_LAYOUT_H", ""]
    lines += [f"#define NESDATA_{p.name.upper()}_SIZE {p.size}" for p in pieces]
    lines += ["", "#endif", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
