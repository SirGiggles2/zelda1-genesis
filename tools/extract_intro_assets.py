_TILE_SPACE  = 0x24
_TILE_PERIOD = 0x63
_TILE_COMMA_GEN  = 512
_TILE_APOSTR_GEN = 513

def _story_tile_for_char(ch: str) -> tuple:
    """Return (tile_idx, is_custom)."""
    if ch == ' ': return (_TILE_SPACE, False)
    if ch == '.': return (_TILE_PERIOD, False)
    if ch == ',': return (_TILE_COMMA_GEN, True)
    if ch == "'": return (_TILE_APOSTR_GEN, True)
    if ch.isdigit(): return (ord(ch) - ord('0'), False)
    if ch.isalpha(): return (0x0A + (ord(ch.upper()) - ord('A')), False)
    return (_TILE_SPACE, False)

def _story_cell(palette: int, tile: int) -> int:
    return ((palette & 3) << 13) | (tile & 0x7FF)

def _vine_l(phase: int) -> int:
    return _story_cell(3, 0xE2 if phase % 2 == 0 else 0xE3)

def _vine_r(phase: int) -> int:
    return _story_cell(3, 0xE3 if phase % 2 == 0 else 0xE2)

def _story_header_row(text: str, pal: int) -> list:
    row = [_story_cell(0, _TILE_SPACE)] * 32
    row[2] = _story_cell(3, 0xE6)
    row[3] = _story_cell(3, 0xE4)
    row[4] = _story_cell(3, 0xE5)
    row[27] = _story_cell(3, 0xE5)
    row[28] = _story_cell(3, 0xE4)
    row[29] = _story_cell(3, 0xE6)
    text = text.upper()
    start = 6 + max(0, (20 - len(text)) // 2)
    for i, ch in enumerate(text):
        if start + i > 25: break
        tile, _ = _story_tile_for_char(ch)
        row[start + i] = _story_cell(pal, tile)
    return row

def _story_body_row(text: str, default_pal: int, pal_overrides: dict, phase: int) -> list:
    row = [_story_cell(0, _TILE_SPACE)] * 32
    row[2] = _vine_l(phase)
    row[29] = _vine_r(phase)
    text = text.upper()
    if len(text) > 25:
        text = text[:25]
    char_pals = [default_pal] * len(text)
    for word, pal in pal_overrides.items():
        word_up = word.upper()
        idx = text.find(word_up)
        while idx >= 0:
            for k in range(len(word_up)):
                if idx + k < len(char_pals):
                    char_pals[idx + k] = pal
            idx = text.find(word_up, idx + 1)
    for i, ch in enumerate(text):
        col = 4 + i
        if col >= 32: break
        tile, _ = _story_tile_for_char(ch)
        row[col] = _story_cell(char_pals[i], tile)
    return row

def _story_empty_vine_row(phase: int) -> list:
    row = [_story_cell(0, _TILE_SPACE)] * 32
    row[2] = _vine_l(phase)
    row[29] = _vine_r(phase)
    return row

def _story_full_vine_row() -> list:
    row = [_story_cell(0, _TILE_SPACE)] * 32
    row[2] = _story_cell(3, 0xE6)
    for c in range(3, 29):
        row[c] = _story_cell(3, 0xE4 if (c - 3) % 2 == 0 else 0xE5)
    row[29] = _story_cell(3, 0xE6)
    return row

