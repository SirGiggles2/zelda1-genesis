def _read_blink_chr() -> bytes:
    """Re-encode heart/rupee/triforce tiles with color_shift=8 for blink anim.

    Output layout (8 NES tiles, 256 bytes Gen 4bpp):
      tile 0-1: NES misc $F2/$F3 (heart top/bot)
      tile 2-3: NES sprite $68/$69 (container heart top/bot)
      tile 4-5: NES sprite $6E/$6F (triforce top/bot)
      tile 6-7: NES sprite $32/$33 (rupee top/bot)
    """
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    sprite_data = (ref_dir / "CommonSpritePatterns.dat").read_bytes() + \
                  (ref_dir / "DemoSpritePatterns.dat").read_bytes()
    misc_data = (ref_dir / "CommonMiscPatterns.dat").read_bytes()
    misc_base = 0xF2  # CommonMiscPatterns starts at NES tile $F2
    TILES = [
        ("misc",   0xF2, 8),
        ("misc",   0xF3, 8),
        ("sprite", 0x68, 8),
        ("sprite", 0x69, 8),
        ("sprite", 0x6E, 8),
        ("sprite", 0x6F, 8),
        ("sprite", 0x32, 8),
        ("sprite", 0x33, 8),
    ]
    gen = bytearray()
    for source, T, shift in TILES:
        if source == "sprite":
            tile = sprite_data[T*16:(T+1)*16]
        else:
            tile = misc_data[(T - misc_base)*16:(T - misc_base + 1)*16]
        gen += nes_tile_to_gen_tile(tile, color_shift=shift)
    return bytes(gen)

def _build_combined_palette() -> list[int]:
    """Build 64-slot Genesis CRAM combining story BG + sprite palettes.

    Reads the story CRAM (already built by _build_story_cram) and the
    NES sprite palette as PALRAM holds it after the story palette record
    (equal to the capture tools/intro_demo/nes_full/palram_3380.bin this
    replaced), then overlays story color overrides for GANON/ZELDA/LINK.
    """
    story = _build_story_cram()
    cram = list(story)
    # GameCube-version story-scroll color overrides:
    #   pal 1 color 1 = bright red  (GANON)
    #   pal 2 color 1 = rupee blue  (ZELDA)
    #   pal 3 color 1 = bright green (LINK)
    cram[1*16 + 1] = 0x000E   # bright red
    cram[2*16 + 1] = 0x0E88   # rupee blue
    cram[3*16 + 1] = 0x00E0   # bright green
    palram = _nes_palram_after_record(STORY_PALETTE_RECORD)
    # NES sprite palettes $3F10-$3F1F (palram bytes 16-31).
    # Pack into slots 4-7 of Gen pals 1, 2, 3.
    for sp in range(3):
        for c in range(4):
            nes_color = palram[16 + sp * 4 + c]
            cram[(sp + 1) * 16 + 4 + c] = nes_color_to_gen_cram(nes_color)
    return cram

def _emit_combined_palette(out_path: Path, cram: list[int]) -> None:
    lines = [
        "/* Auto-generated by tools/extract_intro_assets.py - do not edit. */\n",
        "/* Layout: slots 0-3 = NES BG palette, slots 4-7 = NES sprite palette. */\n",
        "const unsigned short intro_combined_palette[64] = {\n",
    ]
    for i in range(0, 64, 8):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in cram[i:i+8]) + ",\n")
    lines.append("};\n")
    out_path.write_text("".join(lines), encoding="utf-8", newline="\n")

