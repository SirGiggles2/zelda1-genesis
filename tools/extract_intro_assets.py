def _read_title_palette() -> list[int]:
    """NES PALRAM at the title (TitlePaletteTransferRecord, glow phase 1;
    equal to the title capture tools/intro_demo/nes_full/palram_title.bin
    this replaced), packed into the 64-word Genesis CRAM combined layout:
      Gen pal P slots 0-3  = NES BG pal P  (PALRAM $3F00 + P*4)
      Gen pal P slots 4-7  = NES SPR pal P  (PALRAM $3F10 + P*4)
      Gen pal P slots 8-15 = 0 (unused)"""
    pal = _title_palram()
    cram = [0] * 64
    for p in range(4):
        for c in range(4):
            cram[p*16 + c]     = nes_color_to_gen_cram(pal[p*4 + c])
            cram[p*16 + 4 + c] = nes_color_to_gen_cram(pal[16 + p*4 + c])
    return cram

