def _read_title_bg_chr() -> bytes:
    """Concatenate CommonBackgroundPatterns + DemoBackgroundPatterns +
    CommonMiscPatterns and convert to Genesis 4bpp (color_shift=0)."""
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    common = (ref_dir / "CommonBackgroundPatterns.dat").read_bytes()
    demo   = (ref_dir / "DemoBackgroundPatterns.dat").read_bytes()
    misc   = (ref_dir / "CommonMiscPatterns.dat").read_bytes()
    bg_data = common + demo + misc
    n_tiles = len(bg_data) // 16
    gen = bytearray()
    for t in range(n_tiles):
        gen += nes_tile_to_gen_tile(bg_data[t*16:(t+1)*16], color_shift=0)
    return bytes(gen)

def _read_title_sprite_chr() -> bytes:
    """NES sprite pattern table 0 at the title ($0000-$0FFF, 256 tiles):
    CommonSpritePatterns (112 tiles) then DemoSpritePatterns (144), as the
    game uploads them. Converted to Genesis 4bpp with color_shift=4.
    (Equal to the title-frame CHR capture tools/intro_demo/nes_full/
    chr_title.bin, which this replaced.)"""
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    sprite_chr = ((ref_dir / "CommonSpritePatterns.dat").read_bytes() +
                  (ref_dir / "DemoSpritePatterns.dat").read_bytes())
    if len(sprite_chr) != 0x1000:
        raise ValueError(f"sprite pattern table must be 4096 bytes, got {len(sprite_chr)}")
    n_tiles = len(sprite_chr) // 16
    gen = bytearray()
    for t in range(n_tiles):
        gen += nes_tile_to_gen_tile(sprite_chr[t*16:(t+1)*16], color_shift=4)
    return bytes(gen)

def _nes_palram_after_record(record: list[int]) -> list[int]:
    """NES PALRAM after a 32-byte $3F00 transfer record, as BizHawk's PALRAM
    domain shows it: $3F10/$3F14/$3F18/$3F1C are mirrors, so the record's
    sprite color-0 writes land in $3F00/$3F04/$3F08/$3F0C (written last)
    and the mirror cells read 0."""
    if record[:3] != [0x3F, 0x00, 0x20] or len(record) < 35:
        raise ValueError("expected a 32-byte $3F00 palette transfer record")
    pal = list(record[3:35])
    for k in range(4):
        pal[k * 4] = pal[16 + k * 4]
        pal[16 + k * 4] = 0
    return pal

