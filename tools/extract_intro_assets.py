def _emit_chr_array(out_path: Path, symbol: str, data: bytes) -> None:
    """Emit a C array of unsigned chars to a file."""
    lines = [f"/* Auto-generated by tools/extract_intro_assets.py - do not edit. */\n",
             f"const unsigned char {symbol}[{len(data)}] = {{\n"]
    for i in range(0, len(data), 16):
        row = ", ".join(f"0x{b:02X}" for b in data[i:i+16])
        lines.append(f"    {row},\n")
    lines.append("};\n")
    lines.append(f"const unsigned long {symbol}_size = {len(data)};\n")
    out_path.write_text("".join(lines), encoding="utf-8", newline="\n")

def _build_story_cram() -> list[int]:
    """Convert the NES story palette record to a 64-entry Genesis CRAM buffer."""
    # Record layout (NES-style PPU transfer): skip 3-byte header, then 32 NES
    # palette bytes (4 sub-palettes x 8 entries, of which 0..3 are meaningful
    # per sub-palette in NES; Genesis uses 4 palettes x 16 colors).
    nes_bytes = STORY_PALETTE_RECORD[3:3 + 32]
    cram = [0] * 64
    for subpal in range(4):
        for color in range(4):
            nes_idx = nes_bytes[subpal * 4 + color] & 0x3F
            cram[subpal * 16 + color] = nes_color_to_gen_cram(nes_idx)
    return cram

def _emit_palette(out_path: Path, cram: list[int]) -> None:
    lines = [f"/* Auto-generated by tools/extract_intro_assets.py - do not edit. */\n",
             f"const unsigned short intro_palette[64] = {{\n"]
    for i in range(0, 64, 8):
        row = ", ".join(f"0x{v:04X}" for v in cram[i:i+8])
        lines.append(f"    {row},\n")
    lines.append("};\n")
    out_path.write_text("".join(lines), encoding="utf-8", newline="\n")

def _load_nes_chr(path: Path) -> bytes:
    """Read NES 2bpp CHR blob, convert to Genesis 4bpp, return concatenated bytes."""
    nes = path.read_bytes()
    assert len(nes) % 16 == 0, f"{path}: CHR length not multiple of 16"
    gen = bytearray()
    for i in range(0, len(nes), 16):
        gen += nes_tile_to_gen_tile(nes[i:i+16])
    return bytes(gen)

def _parse_ppu_transfer_records(data: bytes) -> list[tuple[int, bytes]]:
    """Parse a stream of NES PPU transfer records (addr_hi, addr_lo, count, data[count]).

    Trailing $FF byte (or any byte that can't start a valid record) terminates.
    Returns [(addr, payload), ...].
    """
    out: list[tuple[int, bytes]] = []
    i = 0
    while i + 3 <= len(data):
        hi = data[i]
        if hi == 0xFF:
            break
        lo = data[i+1]
        n = data[i+2]
        if i + 3 + n > len(data):
            break
        out.append(((hi << 8) | lo, bytes(data[i+3:i+3+n])))
        i += 3 + n
    return out

def _build_nt1_tilemap(raw: bytes) -> tuple[list[int], int]:
    """Parse an NES PPU transfer record stream that fills NT1 + its attribute
    table, fold the attribute bits into per-cell palette indices, and return
    Genesis nametable words.

    Each NES attribute byte covers a 4x4 tile quad; bits 1:0 = top-left 2x2
    palette, 3:2 = top-right, 5:4 = bottom-left, 7:6 = bottom-right.
    Genesis cell word: (palette << 13) | tile_idx.

    Records targeting NT2 ($2800+) are ignored — they describe rows only the
    NES runtime composer reaches, and the native rewrite handles scroll past
    row 29 separately.
    """
    records = _parse_ppu_transfer_records(raw)

    ROWS = 30
    COLS = 32
    tiles = [0] * (ROWS * COLS)
    attrs = [0] * 64  # NT1 attribute table is 64 bytes

    for addr, payload in records:
        if 0x2000 <= addr < 0x23C0:
            off = addr - 0x2000
            for k, b in enumerate(payload):
                idx = off + k
                if idx < len(tiles):
                    tiles[idx] = b
        elif 0x23C0 <= addr < 0x2400:
            off = addr - 0x23C0
            for k, b in enumerate(payload):
                if off + k < len(attrs):
                    attrs[off + k] = b
        # Records into NT2 ($2800+) describe rows that only become visible
        # via runtime composition on the NES; the native rewrite handles
        # scroll past row 29 separately and ignores them here.

    def _pal_for_cell(r: int, c: int) -> int:
        attr_idx = (r // 4) * 8 + (c // 4)
        quad_row = (r >> 1) & 1
        quad_col = (c >> 1) & 1
        shift = (quad_row * 2 + quad_col) * 2
        return (attrs[attr_idx] >> shift) & 3

    cells = [0] * (ROWS * COLS)
    for r in range(ROWS):
        for c in range(COLS):
            tile = tiles[r * COLS + c]
            pal = _pal_for_cell(r, c)
            cells[r * COLS + c] = ((pal & 3) << 13) | (tile & 0x7FF)
    return cells, ROWS

def _build_story_tilemap(ref_dir: Path) -> tuple[list[int], int]:
    raw = (ref_dir / "StoryTileAttrTransferBuf.dat").read_bytes()
    return _build_nt1_tilemap(raw)

def _build_showcase_tilemap(ref_dir: Path) -> tuple[list[int], int]:
    raw = (ref_dir / "GameTitleTransferBuf.dat").read_bytes()
    return _build_nt1_tilemap(raw)

def _emit_handoff_state(out_path: Path, json_path: Path) -> None:
    """Emit INTRO_HANDOFF_EXPECTED struct from the captured handoff state JSON.

    The capture JSON has the shape {field: {"addr": "0x...", "value": "0x.."}}
    plus metadata keys (capture_frame, mode_at_capture, submode_at_capture)
    that describe when the snapshot was taken. The metadata keys are skipped;
    only byte fields with an addr+value pair become struct initializers.
    """
    data = json.loads(json_path.read_text())
    lines = [f"/* Auto-generated by tools/extract_intro_assets.py - do not edit. */\n",
             f'#include "intro_handoff.h"\n\n',
             "const intro_handoff_state_t INTRO_HANDOFF_EXPECTED = {\n"]
    for k, v in data.items():
        if not isinstance(v, dict) or "value" not in v:
            continue
        byte = int(v["value"], 16) & 0xFF
        lines.append(f"    .{k} = 0x{byte:02X},\n")
    lines.append("};\n")
    out_path.write_text("".join(lines), encoding="utf-8", newline="\n")

