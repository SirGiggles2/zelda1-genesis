def _build_story_tilemap_gc() -> tuple:
    """Build the GameCube-version story tilemap (matches compose_story_tilemap.py)."""
    cells: list = []
    cells.extend(_story_header_row("THE LEGEND OF ZELDA", 1))
    cells.extend(_story_empty_vine_row(0))
    cells.extend(_story_empty_vine_row(1))
    all_lines = _STORY_LINES
    phase = 0
    for i, line in enumerate(all_lines):
        cells.extend(_story_body_row(line, 0, _STORY_OVERRIDES, phase))
        phase += 1
        if i < len(all_lines) - 1:
            cells.extend(_story_empty_vine_row(phase))
            phase += 1
    cells.extend(_story_empty_vine_row(phase))
    phase += 1
    cells.extend(_story_full_vine_row())
    blank_row = [_story_cell(0, _TILE_SPACE)] * 32
    while len(cells) // 32 < 30:
        cells.extend(blank_row)
    rows = len(cells) // 32
    return cells, rows

