def _read_common_bg_chr() -> bytes:
    """CommonBackgroundPatterns.dat -> Genesis 4bpp (color_shift=0)."""
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    data = (ref_dir / "CommonBackgroundPatterns.dat").read_bytes()
    gen = bytearray()
    for i in range(0, len(data) - 15, 16):
        gen += nes_tile_to_gen_tile(data[i:i+16], color_shift=0)
    return bytes(gen)

def _read_sprite_chr() -> bytes:
    """CommonSpritePatterns + DemoSpritePatterns -> Genesis 4bpp (color_shift=4)."""
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    data = (ref_dir / "CommonSpritePatterns.dat").read_bytes() + \
           (ref_dir / "DemoSpritePatterns.dat").read_bytes()
    gen = bytearray()
    for i in range(0, (len(data) // 16) * 16, 16):
        gen += nes_tile_to_gen_tile(data[i:i+16], color_shift=4)
    return bytes(gen)

def _read_misc_chr() -> bytes:
    """CommonMiscPatterns.dat -> Genesis 4bpp (color_shift=4)."""
